"""
Уровень 1 — базовый

1. Развернуть строку
Дана строка s. Получите её в обратном порядке, используя только срез.
"""
s = "программирование"
# ожидается: "еинавориммаргорп"

s = s[-1::-1]
print(s)

"""
2. Каждый второй символ
Дан список nums. Получите список, 
содержащий каждый второй элемент, начиная с первого (индексы 0, 2, 4, ...).
"""
nums = [10, 20, 30, 40, 50, 60, 70]
# ожидается: [10, 30, 50, 70]
nums = nums[1: : 2]
print(nums)

"""
3. Убрать первый и последний
Дана строка s. Получите её без первого и последнего символа одним срезом.
"""
s = "срез"
# ожидается: "ре"
s = s[1:len(s)-1]
print(s)

"""
Уровень 2 — средний

4. Последние N в обратном порядке
Даны список data и число n. 
Получите последние n элементов в обратном порядке (одним выражением со срезом).
"""
data = [1, 2, 3, 4, 5, 6, 7, 8]
n = 3
# ожидается: [8, 7, 6]
data = data[ :-n-1: -1] #-n-1 = -4 строго до 4 элементов справа-налево
print(data)

""""

5. Центральная часть списка
Дан список arr чётной длины. 
Получите его среднюю половину (центральные элементы), одним срезом.
"""
arr = [0, 1, 2, 3, 4, 5, 6, 7]
# ожидается: [2, 3, 4, 5]  (если трактовать "среднюю половину" как половину длины по центру)
#Подсказка: подумайте про отрицательные индексы и len(arr)//4 или аналоги.
arr = arr[len(arr)//4 : -len(arr)//4]
print(arr)
"""
6. Замена середины через срезы
Дан список a и список b. 
Замените в a элементы с индекса 2 по 5 (не включая 5) на весь список b, 
используя присваивание по срезу (без if).
"""
a = [0, 1, 2, 3, 4, 5, 6]
b = [100, 200]
# ожидается: [0, 1, 100, 200, 5, 6]
a[2 : 5] = b
print(a)

"""
Уровень 3 — продвинутый

7. Циклический сдвиг срезом
Дан список lst и число k. Сдвиньте список влево на k позиций, 
используя только срезы и конкатенацию (без циклов и if). 
Считайте, что 0 <= k <= len(lst).
"""
lst = [1, 2, 3, 4, 5]
k = 2
# ожидается: [3, 4, 5, 1, 2]
lst = lst[k : ] + lst[ : k]
print(lst)  # [3, 4, 5, 1, 2]

"""
8. «Палиндромная» проверка через срез
Дана строка s. 
Получите булево значение True/False — является ли строка палиндромом — 
без if, без циклов, только сравнение со срезом. 
(Регистр и пробелы можно не учитывать — 
но тоже без if: используйте методы lower() и replace().)
"""
s = "А роза упала на лапу Азора"
s = s.lower().replace(" ", "")
# ожидается: True
palindrom = s[ : : ] == s[-len(s) : : ]
print(palindrom)

"""
9. Переворот каждой «половины»
Дан список arr чётной длины. 
Поменяйте местами две его половины И разверните каждую половину, 
всё через срезы (без if и циклов). 
Фактически получите: arr[:mid][::-1] + arr[mid:][::-1].
"""
arr = [1, 2, 3, 4, 5, 6]
# ожидается: [3, 2, 1, 6, 5, 4]
#Дополнительно: объясните, 
# чем результат отличается от простого arr[::-1] и почему.

mid = len(arr)//2
arr = arr[ : mid][::-1] + arr[mid :][::-1] 
print(arr)